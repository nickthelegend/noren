// Writes a Foundry fixture from the real Kohaku/snarkjs proof produced in the spike.
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import type { Address, Hex } from 'viem';

type Proof = {
  pA: bigint[];
  pB: bigint[][];
  pC: bigint[];
  pubSignals: bigint[];
};

type FixtureInput = {
  contractsDir: string;
  checkout: Address;
  pool: Address;
  entrypoint: Address;
  usdc: Address;
  merchant: Address;
  merchant2: Address;
  invoiceId: Hex;
  receiptCommitment: Hex;
  amount: bigint;
  expiry: bigint;
  refundPrecommitment: bigint;
  proof: Proof;
};

export function writeFoundryFixture(input: FixtureInput): void {
  const { contractsDir, checkout, pool, entrypoint, usdc, merchant, merchant2, invoiceId,
    receiptCommitment, amount, expiry, refundPrecommitment, proof } = input;
  const addr = (value: Address) => `address(uint160(${BigInt(value)}))`;
  const lines = [
    '// SPDX-License-Identifier: MIT',
    'pragma solidity 0.8.28;',
    "import {IPrivacyPool} from 'interfaces/IPrivacyPool.sol';",
    "import {ProofLib} from 'contracts/lib/ProofLib.sol';",
    '/// @notice Generated by scripts/gen-fixtures.ts from a real Kohaku proof.',
    'library Fixture {',
    `  function checkout() internal pure returns (address) { return ${addr(checkout)}; }`,
    `  function pool() internal pure returns (address) { return ${addr(pool)}; }`,
    `  function entrypoint() internal pure returns (address) { return ${addr(entrypoint)}; }`,
    `  function usdc() internal pure returns (address) { return ${addr(usdc)}; }`,
    `  function merchant() internal pure returns (address) { return ${addr(merchant)}; }`,
    `  function merchant2() internal pure returns (address) { return ${addr(merchant2)}; }`,
    `  function invoiceId() internal pure returns (bytes32) { return ${invoiceId}; }`,
    `  function receiptCommitment() internal pure returns (bytes32) { return ${receiptCommitment}; }`,
    `  function amount() internal pure returns (uint256) { return ${amount}; }`,
    `  function expiry() internal pure returns (uint256) { return ${expiry}; }`,
    `  function refundPrecommitment() internal pure returns (uint256) { return ${refundPrecommitment}; }`,
    '  function withdrawal() internal pure returns (IPrivacyPool.Withdrawal memory w) {',
    '    w.processooor = checkout();',
    '    w.data = abi.encode(invoiceId(), merchant(), amount(), expiry(), refundPrecommitment(), receiptCommitment());',
    '  }',
    '  function proof() internal pure returns (ProofLib.WithdrawProof memory p) {',
    ...proof.pA.map((value, i) => `    p.pA[${i}] = ${value};`),
    ...proof.pB.flatMap((row, i) => row.map((value, j) => `    p.pB[${i}][${j}] = ${value};`)),
    ...proof.pC.map((value, i) => `    p.pC[${i}] = ${value};`),
    ...proof.pubSignals.map((value, i) => `    p.pubSignals[${i}] = ${value};`),
    '  }',
    '}',
  ];
  const fixtureDir = resolve(contractsDir, 'test/fixtures');
  mkdirSync(fixtureDir, { recursive: true });
  writeFileSync(resolve(fixtureDir, 'Fixture.sol'), lines.join('\n') + '\n');
}
