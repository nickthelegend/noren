// Collects every event declared by Noren's contracts and by 1inch Aqua / SwapVM into src/tx-events.ts, so the
// local-fork transaction page can decode logs. Run from the repo root: node packages/web/scripts/gen-tx-events.mjs
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const roots = ["packages/contracts/src", "packages/robinhood/contracts/src", "packages/arc-credit", "packages/bridge-settlement", "packages/world-id", "packages/aqua/swapvm-ext/src", "packages/aqua/node_modules/@1inch/aqua/src", "packages/aqua/node_modules/@1inch/swap-vm/src"];
const prim = /^(address|bool|string|bytes\d*|u?int\d*)(\[\d*\])*$/;
const skipDir = new Set(["node_modules", "lib", "test", "out", "cache", "script"]);
const files = [];
const walk = (d) => { let es; try { es = readdirSync(d); } catch { return; } for (const e of es) { const p = join(d, e); const s = statSync(p); if (s.isDirectory()) { if (!skipDir.has(e) || d.endsWith("@1inch")) walk(p); } else if (e.endsWith(".sol")) files.push(p); } };
for (const r of roots) walk(r);
const out = new Map();
for (const f of files) {
  const src = readFileSync(f, "utf8").replace(/\/\/.*$/gm, "").replace(/\/\*[\s\S]*?\*\//g, "");
  const enums = new Set([...src.matchAll(/enum\s+(\w+)/g)].map((m) => m[1]));
  for (const m of src.matchAll(/\bevent\s+(\w+)\s*\(([\s\S]*?)\)\s*(anonymous\s*)?;/g)) {
    if (m[3]) continue;
    const params = m[2].split(",").map((s) => s.trim().replace(/\s+/g, " ")).filter(Boolean).map((p) => { const [t, ...rest] = p.split(" "); return [enums.has(t) ? "uint8" : t, ...rest].join(" "); });
    if (!params.every((p) => prim.test(p.split(" ")[0]))) continue;
    const sig = `${m[1]}(${params.map((p) => p.split(" ")[0]).join(",")})`;
    if (!out.has(sig)) out.set(sig, { text: `event ${m[1]}(${params.join(", ")})`, from: relative(process.cwd(), f) });
  }
}
// The Kohaku privacy-pool and entrypoint events, as the Kohaku SDK declares them.
const pnpm = "node_modules/.pnpm";
for (const d of readdirSync(pnpm).filter((x) => x.startsWith("@kohaku-eth+privacy-pools@"))) {
  const f = join(pnpm, d, "node_modules/@kohaku-eth/privacy-pools/dist/index.js");
  let js; try { js = readFileSync(f, "utf8"); } catch { continue; }
  for (const m of js.matchAll(/"event (\w+)\(([^)"]*)\)"/g)) {
    const sig = `${m[1]}(${m[2].split(",").map((x) => x.trim().split(" ")[0]).filter(Boolean).join(",")})`;
    if (!out.has(sig)) out.set(sig, { text: `event ${m[1]}(${m[2]})`, from: "@kohaku-eth/privacy-pools" });
  }
  break;
}
const list = [...out.values()].sort((a, b) => a.text.localeCompare(b.text));
writeFileSync("packages/web/src/tx-events.ts", `/** Generated by packages/web/scripts/gen-tx-events.mjs: every event in Noren's contracts and in 1inch Aqua / SwapVM. */\nexport const EVENTS: string[] = [\n${list.map((e) => `  ${JSON.stringify(e.text)}, // ${e.from}`).join("\n")}\n];\n`);
console.log(`${list.length} events from ${files.length} files`);
