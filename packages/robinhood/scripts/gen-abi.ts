import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { resolve } from 'node:path'

const root = resolve(fileURLToPath(new URL('..', import.meta.url)))
const names = ['NorenAssetOracle', 'NorenVault', 'NorenGateway', 'NorenCredit', 'NorenLiquidity', 'NorenDepositVault', 'NorenReputation', 'NorenBorrow', 'NorenDutchAuction', 'NorenCreditLens'] as const
let output = "// Generated by scripts/gen-abi.ts from Forge artifacts. Do not edit.\nimport { parseAbi } from 'viem'\n"
for (const name of names) {
  const artifact = JSON.parse(await readFile(resolve(root, 'contracts/out', name + '.sol', name + '.json'), 'utf8')) as { abi: unknown }
  output += `export const ${name[0].toLowerCase() + name.slice(1)}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const\n`
}
const erc20 = [
  'function balanceOf(address) view returns (uint256)',
  'function allowance(address,address) view returns (uint256)',
  'function approve(address,uint256) returns (bool)',
  'function decimals() view returns (uint8)',
  'function symbol() view returns (string)',
  'function name() view returns (string)',
  'function nonces(address) view returns (uint256)',
  'function DOMAIN_SEPARATOR() view returns (bytes32)',
  'function permit(address,address,uint256,uint256,uint8,bytes32,bytes32)',
]
const aggregator = ['function decimals() view returns (uint8)', 'function latestRoundData() view returns (uint80,int256,uint256,uint256,uint80)']
const stock = ['function uiMultiplier() view returns (uint256)', 'function balanceOfUI(address) view returns (uint256)']
// 1inch Aqua registry and Uniswap v4 V4Quoter: the calls the SDK makes, from their published ABIs.
const aqua = [
  'function rawBalances(address maker, address app, bytes32 strategyHash, address token) view returns (uint248 balance, uint8 tokensCount)',
  'function safeBalances(address maker, address app, bytes32 strategyHash, address token0, address token1) view returns (uint256, uint256)',
  'function ship(address app, bytes strategy, address[] tokens, uint256[] amounts) returns (bytes32 strategyHash)',
  'function dock(address app, bytes32 strategyHash, address[] tokens)',
  'event Shipped(address maker, address app, bytes32 strategyHash, bytes strategy)',
  'event Pulled(address maker, address app, bytes32 strategyHash, address token, uint256 amount)',
  'event Pushed(address maker, address app, bytes32 strategyHash, address token, uint256 amount)',
]
const v4Quoter = [
  'struct PoolKey { address currency0; address currency1; uint24 fee; int24 tickSpacing; address hooks; }',
  'struct QuoteExactSingleParams { PoolKey poolKey; bool zeroForOne; uint128 exactAmount; bytes hookData; }',
  'function quoteExactInputSingle(QuoteExactSingleParams params) returns (uint256 amountOut, uint256 gasEstimate)',
]
output += `export const aquaAbi = parseAbi(${JSON.stringify(aqua)} as const)\nexport const v4QuoterAbi = parseAbi(${JSON.stringify(v4Quoter)} as const)\n`
output += `export const erc20PermitAbi = parseAbi(${JSON.stringify(erc20)} as const)\nexport const aggregatorV3Abi = parseAbi(${JSON.stringify(aggregator)} as const)\nexport const stockTokenAbi = parseAbi(${JSON.stringify(stock)} as const)\n`
await mkdir(resolve(root, 'sdk/src'), { recursive: true })
await writeFile(resolve(root, 'sdk/src/abi.ts'), output)
